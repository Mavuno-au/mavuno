create function public.is_reserved_username(p_username text)
returns boolean
language sql
immutable
set search_path = ''
as $$
  select lower(p_username) = any (array[
    'admin', 'administrator', 'mavuno', 'support', 'help', 'moderator', 'moderation', 'settings',
    'login', 'signup', 'logout', 'api', 'about', 'rules', 'privacy', 'terms', 'discover', 'spaces',
    'events', 'opportunities', 'messages', 'notifications', 'saved', 'nearby', 'search',
    'onboarding', 'auth', 'official', 'staff', 'root', 'null', 'deleted', 'unavailable'
  ])
$$;

create function public.normalise_profile()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.username := lower(trim(new.username));
  if (tg_op = 'INSERT' or new.username is distinct from old.username)
     and public.is_reserved_username(new.username) then
    raise exception 'That username is reserved' using errcode = '23514';
  end if;
  new.display_name := trim(new.display_name);
  new.bio := trim(coalesce(new.bio, ''));
  new.interests := array(select distinct lower(trim(i)) from unnest(new.interests) i where trim(i) <> '');
  new.languages := array(select distinct lower(trim(l)) from unnest(new.languages) l where trim(l) <> '');
  return new;
end;
$$;

create trigger profiles_normalise before insert or update on public.profiles
  for each row execute function public.normalise_profile();

