create function public.update_follow_counts()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    update public.profiles set followers_count = followers_count + 1 where id = new.followee_id;
    update public.profiles set following_count = following_count + 1 where id = new.follower_id;
    return new;
  end if;
  update public.profiles set followers_count = greatest(followers_count - 1, 0) where id = old.followee_id;
  update public.profiles set following_count = greatest(following_count - 1, 0) where id = old.follower_id;
  return old;
end;
$$;

create trigger follows_counts after insert or delete on public.follows
  for each row execute function public.update_follow_counts();

-- Blocking removes follows both ways. Unblocking does not restore them.
create function public.handle_block()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  delete from public.follows
  where (follower_id = new.blocker_id and followee_id = new.blocked_id)
     or (follower_id = new.blocked_id and followee_id = new.blocker_id);
  return new;
end;
$$;

create trigger blocks_unfollow after insert on public.blocks
  for each row execute function public.handle_block();

