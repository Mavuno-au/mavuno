-- ---------------------------------------------------------------------------
-- Person profiles follow auth.users
-- ---------------------------------------------------------------------------

create function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_meta jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
  v_username text := lower(coalesce(v_meta ->> 'username', ''));
  v_display text := coalesce(
    nullif(trim(v_meta ->> 'display_name'), ''),
    nullif(trim(v_meta ->> 'full_name'), ''),
    nullif(trim(v_meta ->> 'name'), '')
  );
  v_avatar text := v_meta ->> 'avatar_url';
begin
  if v_username !~ '^[a-z0-9_]{3,30}$'
     or public.is_reserved_username(v_username)
     or exists (select 1 from public.profiles where username = v_username) then
    v_username := 'member_' || substr(replace(new.id::text, '-', ''), 1, 10);
  end if;

  insert into public.profiles (id, account_type, username, display_name, avatar_url)
  values (
    new.id, 'person', v_username, left(coalesce(v_display, v_username), 60),
    case when v_avatar ~ '^https://' then v_avatar end
  );
  return new;
end;
$$;

create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

create function public.handle_deleted_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  -- Organisations the person owns alone go with them.
  delete from public.profiles o
  where o.account_type = 'organisation'
    and exists (select 1 from public.organisation_members m where m.org_id = o.id and m.user_id = old.id and m.role = 'owner')
    and not exists (select 1 from public.organisation_members m where m.org_id = o.id and m.user_id <> old.id and m.role = 'owner');

  delete from public.profiles where id = old.id;
  return old;
end;
$$;

create trigger on_auth_user_deleted after delete on auth.users
  for each row execute function public.handle_deleted_user();

