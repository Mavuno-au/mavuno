-- Mavuno core: cities, profiles (people and organisations), private settings,
-- follows, blocks and mutes.
--
-- Conventions:
--   * Every table has row level security. Writes that need more than a one-row
--     check go through SECURITY DEFINER functions with an empty search_path.
--   * A profile is a person (id = auth.users.id) or an organisation (its own id,
--     run by people listed in organisation_members).
--   * public.profiles holds only what is shown publicly. Preferences, roles and
--     suspensions live in public.profile_settings, readable by the owner only.
--   * Locations are city level. Coordinates on public.cities are city centroids;
--     nothing more precise is stored about anyone.

create extension if not exists pg_trgm with schema extensions;

create type public.account_type as enum ('person', 'organisation');
create type public.site_role as enum ('member', 'moderator', 'admin');
create type public.dm_policy as enum ('everyone', 'following', 'nobody');
create type public.org_role as enum ('owner', 'admin', 'editor');

-- ---------------------------------------------------------------------------
-- Cities
-- ---------------------------------------------------------------------------

create table public.cities (
  id smallint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9-]{2,40}$'),
  name text not null,
  state text not null check (state in ('ACT', 'NSW', 'NT', 'QLD', 'SA', 'TAS', 'VIC', 'WA')),
  latitude double precision not null,
  longitude double precision not null
);

alter table public.cities enable row level security;
create policy "Cities are public" on public.cities for select using (true);

create function public.city_distance_km(a smallint, b smallint)
returns double precision
language sql
stable
set search_path = ''
as $$
  select 6371 * 2 * asin(sqrt(
    power(sin(radians(cb.latitude - ca.latitude) / 2), 2)
    + cos(radians(ca.latitude)) * cos(radians(cb.latitude))
    * power(sin(radians(cb.longitude - ca.longitude) / 2), 2)
  ))
  from public.cities ca, public.cities cb
  where ca.id = a and cb.id = b
$$;

-- ---------------------------------------------------------------------------
-- Site settings (one row, changed by admins)
