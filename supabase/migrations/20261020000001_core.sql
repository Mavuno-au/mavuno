alter table public.mutes enable row level security;

create function public.is_blocked_between(a uuid, b uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select a is not null and b is not null and exists (
    select 1 from public.blocks
    where (blocker_id = a and blocked_id = b) or (blocker_id = b and blocked_id = a)
  )
$$;

-- Either side of a block with the viewer.
create function public.is_blocked_with_viewer(p_profile_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select auth.uid() is not null and public.is_blocked_between(auth.uid(), p_profile_id)
$$;

create function public.is_muted_by_viewer(p_profile_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select auth.uid() is not null and exists (
    select 1 from public.mutes where muter_id = auth.uid() and muted_id = p_profile_id
  )
$$;

