create function public.is_moderator()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profile_settings
    where id = auth.uid() and site_role in ('moderator', 'admin')
  )
$$;

create function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.profile_settings where id = auth.uid() and site_role = 'admin')
$$;

-- The signed-in person exists and is not suspended.
create function public.is_active_member()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    join public.profile_settings s on s.id = p.id
    where p.id = auth.uid() and p.account_type = 'person'
      and (s.suspended_until is null or s.suspended_until < now())
  )
$$;

-- The signed-in person can act as the profile: themselves, or an organisation
-- they help run.
create function public.can_act_as(p_profile_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select p_profile_id is not null and auth.uid() is not null and (
    p_profile_id = auth.uid()
    or exists (select 1 from public.organisation_members where org_id = p_profile_id and user_id = auth.uid())
  )
$$;

create function public.can_manage_org(p_org_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.organisation_members
    where org_id = p_org_id and user_id = auth.uid() and role in ('owner', 'admin')
  )
$$;

-- Effective identity colour: the chosen one, or one derived from the id.
create function public.profile_colour(p_colour smallint, p_id uuid)
returns smallint
language sql
immutable
set search_path = ''
as $$
  select coalesce(p_colour, (abs(hashtext(p_id::text)) % 6)::smallint)
$$;

