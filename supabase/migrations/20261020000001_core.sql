create table public.site_settings (
  id boolean primary key default true check (id),
  -- Hold posts and listings from members without a good reputation for review.
  premoderation boolean not null default true,
  translations boolean not null default true,
  updated_at timestamptz not null default now()
);

insert into public.site_settings default values;

alter table public.site_settings enable row level security;
create policy "Site settings are public" on public.site_settings for select using (true);
revoke insert, update, delete on public.site_settings from anon, authenticated;

-- ---------------------------------------------------------------------------
-- Profiles
-- ---------------------------------------------------------------------------

create table public.profiles (
  id uuid primary key default gen_random_uuid(),
  account_type public.account_type not null default 'person',
  username text not null unique check (username ~ '^[a-z0-9_]{3,30}$'),
  display_name text not null check (char_length(display_name) between 1 and 60),
  bio text not null default '' check (char_length(bio) <= 300),
  avatar_url text check (avatar_url ~ '^https?://'),
  banner_url text check (banner_url ~ '^https?://'),
  -- One of six identity colours (avatar ring, handle dot). Null means automatic.
  colour smallint check (colour between 0 and 5),
  city_id smallint references public.cities (id) on delete set null,
  heritage text check (char_length(heritage) <= 60),
  pronouns text check (char_length(pronouns) <= 30),
  interests text[] not null default '{}' check (cardinality(interests) <= 15),
  languages text[] not null default '{en}' check (cardinality(languages) <= 12),
  website text check (website ~ '^https?://' and char_length(website) <= 200),
  links jsonb not null default '[]'::jsonb
    check (jsonb_typeof(links) = 'array' and jsonb_array_length(links) <= 5),
  headline text check (char_length(headline) <= 100),
  occupation text check (char_length(occupation) <= 80),
  company text check (char_length(company) <= 80),
  industry text check (char_length(industry) <= 60),
  open_to text[] not null default '{}' check (cardinality(open_to) <= 6),
  org_category text check (char_length(org_category) <= 60),
  org_verified boolean not null default false,
  pinned_post_id uuid,
  followers_count integer not null default 0,
  following_count integer not null default 0,
  posts_count integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index profiles_city_idx on public.profiles (city_id);
create index profiles_username_trgm_idx on public.profiles using gin (username extensions.gin_trgm_ops);
create index profiles_display_name_trgm_idx on public.profiles using gin (lower(display_name) extensions.gin_trgm_ops);
create index profiles_interests_idx on public.profiles using gin (interests);

alter table public.profiles enable row level security;
create policy "Profiles are public" on public.profiles for select using (true);

create table public.profile_settings (
  id uuid primary key references public.profiles (id) on delete cascade,
  site_role public.site_role not null default 'member',
  suspended_until timestamptz,
  dm_policy public.dm_policy not null default 'everyone',
  read_receipts boolean not null default true,
  -- Appear in Nearby and in suggestions.
  discoverable boolean not null default true,
  -- Language posts are translated into. Null follows the browser.
  translation_language text check (translation_language ~ '^[a-z]{2,3}$'),
  feed_languages_only boolean not null default false,
  onboarded_at timestamptz
);

alter table public.profile_settings enable row level security;

create table public.organisation_members (
  org_id uuid not null references public.profiles (id) on delete cascade,
  user_id uuid not null references public.profiles (id) on delete cascade,
  role public.org_role not null default 'editor',
  created_at timestamptz not null default now(),
  primary key (org_id, user_id)
);

create index organisation_members_user_idx on public.organisation_members (user_id);
alter table public.organisation_members enable row level security;

