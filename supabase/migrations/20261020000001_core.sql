create function public.check_organisation_member()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not exists (select 1 from public.profiles where id = new.org_id and account_type = 'organisation') then
    raise exception 'Not an organisation' using errcode = '23514';
  end if;
  if not exists (select 1 from public.profiles where id = new.user_id and account_type = 'person') then
    raise exception 'Only people can run organisations' using errcode = '23514';
  end if;
  return new;
end;
$$;

create trigger organisation_members_check before insert or update on public.organisation_members
  for each row execute function public.check_organisation_member();

create function public.keep_organisation_owner()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if old.role = 'owner'
     and exists (select 1 from public.profiles where id = old.org_id)
     and not exists (select 1 from public.organisation_members where org_id = old.org_id and role = 'owner') then
    raise exception 'Hand over ownership before leaving' using errcode = '23514';
  end if;
  return old;
end;
$$;

create trigger organisation_members_keep_owner after delete or update on public.organisation_members
  for each row execute function public.keep_organisation_owner();

create function public.create_organisation(
  p_username text,
  p_display_name text,
  p_bio text default '',
  p_category text default null,
  p_city_id smallint default null,
  p_website text default null
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id uuid;
begin
  if not public.is_active_member() then
    raise exception 'Sign in to create an organisation' using errcode = '42501';
  end if;
  if (select count(*) from public.organisation_members where user_id = auth.uid() and role = 'owner') >= 10 then
    raise exception 'You can own up to 10 organisations' using errcode = '23514';
  end if;

  insert into public.profiles (account_type, username, display_name, bio, org_category, city_id, website)
  values ('organisation', p_username, p_display_name, coalesce(p_bio, ''), nullif(trim(p_category), ''), p_city_id, nullif(trim(p_website), ''))
  returning id into v_id;

  insert into public.organisation_members (org_id, user_id, role) values (v_id, auth.uid(), 'owner');
  return v_id;
end;
$$;

create function public.set_organisation_role(p_org_id uuid, p_user_id uuid, p_role public.org_role)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not exists (
    select 1 from public.organisation_members where org_id = p_org_id and user_id = auth.uid() and role = 'owner'
  ) then
    raise exception 'Only owners can change roles' using errcode = '42501';
  end if;
  update public.organisation_members set role = p_role where org_id = p_org_id and user_id = p_user_id;
end;
$$;

-- Deletes an organisation. Owners only.
create function public.delete_organisation(p_org_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not exists (
    select 1 from public.organisation_members where org_id = p_org_id and user_id = auth.uid() and role = 'owner'
  ) then
    raise exception 'Only owners can delete an organisation' using errcode = '42501';
  end if;
  delete from public.profiles where id = p_org_id and account_type = 'organisation';
end;
$$;
